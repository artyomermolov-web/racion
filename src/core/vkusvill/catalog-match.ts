// Сопоставление ингредиента рецепта с каталогом Racion ПО НАЗВАНИЮ (тикет 05,
// доработка). Чистый модуль без сети/БД. Импорт рецептов ВВ ссылается на товары по
// id, но нужный продукт часто уже есть в каталоге под другим названием/словоформой
// («Сахар»→«Сахар-песок», «Яблоки»→«Яблоко», «Томаты»→«Помидоры»). Здесь —
// матчер, который это ловит: нормализация + лёгкий русский стеммер + словарь
// синонимов + выбор канонического варианта для родовых слов.
//
// Отличие от `matchIngredient` (match.ts, ре-сорс seed↔товар ВВ): тот при
// неоднозначности возвращает null (осторожность важнее охвата — нельзя повесить
// чужие КБЖУ/цену). Здесь наоборот: рецепту нужен хоть какой-то разумный продукт,
// поэтому родовое «молоко» осознанно кладём на канонический вариант, а не бросаем.

import { normalizeName } from "./match";

// Порог совпадения по названию. 0.5 нужен для двухсловных запросов, где с продуктом
// совпадает лишь его главное слово («Соль морская»↔«Соль поваренная», «Сахарный
// песок»↔«Сахар-песок» = 0.5). Ложные матчи по форм-слову («Паста мисо»↔«Томатная
// паста») отсекаются иначе — форм-слова (паста/соус/крупа) в STOPWORDS.
const CATALOG_THRESHOLD = 0.5;

// Окончания для лёгкого стемминга (по убыванию длины — режем самое длинное первым).
// Цель — свести словоформы к общему корню: яблоки/яблоко→яблок, помидоры→помидор,
// муку/муки→мук. Срезаем только если корень остаётся ≥3 символов (не калечим «рис»).
const ENDINGS = [
  "иями", "ами", "ями",
  "ов", "ев", "ей", "ам", "ям", "ах", "ях", "ою", "ею",
  "ая", "яя", "ое", "ее", "ые", "ие", "ый", "ий", "ой", "ым", "им", "ом", "ем",
  "ую", "юю",
  "а", "я", "о", "е", "ы", "и", "у", "ю", "ь", "й",
];

/** Лёгкий стемминг русского слова: срезает одно распознанное окончание (корень ≥3). */
export function stemWord(token: string): string {
  for (const e of ENDINGS) {
    if (token.length - e.length >= 3 && token.endsWith(e)) {
      return token.slice(0, token.length - e.length);
    }
  }
  return token;
}

// Служебные слова рецептов — не несут смысла для сопоставления продукта.
const STOPWORDS = new Set([
  "и", "с", "со", "из", "для", "на", "в", "по", "до", "без", "или",
  "свеж", "вкус", "натуральн", "готов",
  // Форм-слова: сами по себе не идентифицируют продукт (нужен качественник), и
  // именно они дают ложные матчи при низком пороге. Отбрасываем с обеих сторон:
  // «гречневая крупа»→гречка, «арахисовая паста»→арахисовая, «Паста мисо»→null.
  "круп", "паст", "соус",
]);

// Фразовые синонимы: применяются к нормализованной строке ДО токенизации, когда
// пара слов означает конкретный продукт каталога с иным набором слов.
const PHRASE_SYNONYMS: [RegExp, string][] = [
  [/раст[а-я]*\s+масл[а-я]*/g, "масло подсолнечное"], // растительное масло
  [/подсолнечн[а-я]*\s+масл[а-я]*/g, "масло подсолнечное"],
  [/оливков[а-я]*\s+масл[а-я]*/g, "масло оливковое"],
  [/сливочн[а-я]*\s+масл[а-я]*/g, "масло сливочное"],
  [/сладк[а-я]*\s+пер[а-я]*/g, "перец болгарский"], // сладкий перец
  [/болгарск[а-я]*\s+пер[а-я]*/g, "перец болгарский"],
  [/зубчик[а-я]*\s+чеснок[а-я]*/g, "чеснок"],
  [/дол[а-я]*\s+чеснок[а-я]*/g, "чеснок"], // долька/дольки чеснока
  [/сыр\s+тверд[а-я]*|тверд[а-я]*\s+сыр/g, "сыр российский"], // твёрдый сыр → Российский
];

// Синонимы на уровне корня (после стемминга): слова с нулевым лексическим
// пересечением, но одним продуктом. Ключ и значение — уже стеммированные корни.
const TOKEN_SYNONYMS: Record<string, string> = {
  томат: "помидор",
  картошк: "картофел",
  картофелин: "картофел",
  морковк: "морков",
  луковиц: "лук",
  курочк: "куриц",
  гречнев: "гречк", // «гречневая крупа» → гречка
  огурец: "огурц", // беглая гласная: стеммер даёт «огурец», мн.ч. → «огурц»
};

// Канонический выбор для родового слова: голое «сыр»/«яйцо» одинаково близко к
// нескольким вариантам каталога. Ключ — корень запроса из одного слова; значение —
// корень, который обязан присутствовать в названии выбранного продукта.
const CANONICAL: Record<string, string> = {
  сыр: "российск",
  яйц: "курин",
};

/** Нормализация + фразовые синонимы + токенизация + стемминг + токен-синонимы. */
export function canonicalStems(name: string): string[] {
  let s = normalizeName(name);
  for (const [re, rep] of PHRASE_SYNONYMS) s = s.replace(re, rep);
  const out: string[] = [];
  for (const raw of s.split(" ")) {
    if (!raw) continue;
    const stem = stemWord(raw);
    if (STOPWORDS.has(stem) || STOPWORDS.has(raw)) continue;
    out.push(TOKEN_SYNONYMS[stem] ?? stem);
  }
  return out;
}

/** Коэффициент Дайса двух множеств корней. */
function dice(a: Set<string>, b: Set<string>): number {
  if (a.size === 0 || b.size === 0) return 0;
  let inter = 0;
  for (const t of a) if (b.has(t)) inter++;
  return (2 * inter) / (a.size + b.size);
}

interface Scored<T> {
  c: T;
  idx: number;
  score: number;
  tokens: number;
}

/** Лучший кандидат: выше score, при равенстве — «проще» название, затем порядок. */
function pickBest<T>(scored: Scored<T>[]): T {
  return scored
    .slice()
    .sort((a, b) => b.score - a.score || a.tokens - b.tokens || a.idx - b.idx)[0].c;
}

/**
 * Сопоставляет название ингредиента рецепта с наиболее подходящим продуктом
 * каталога по стеммированным корням (с синонимами). Родовое слово ложится на
 * канонический вариант (см. CANONICAL). Возвращает продукт или null (ничего не
 * прошло порог). Осознанно НЕ бросает при неоднозначности — рецепту нужен продукт.
 */
export function matchCatalogIngredient<T extends { name: string }>(
  name: string,
  catalog: readonly T[],
): T | null {
  const q = canonicalStems(name);
  if (q.length === 0) return null;
  const qset = new Set(q);

  const all: Scored<T>[] = catalog.map((c, idx) => {
    const cs = canonicalStems(c.name);
    return { c, idx, score: dice(qset, new Set(cs)), tokens: cs.length };
  });

  // Родовое слово из одного корня с заданным каноном — предпочитаем канонический
  // вариант ДО порога: у него счёт может быть ниже порога из-за лишних токенов в
  // названии («яйцо» ↔ «Яйцо куриное С1» = 0.5), но продукт заведомо правильный.
  // score > 0 гарантирует, что корень запроса присутствует в кандидате: иначе
  // подсказка (напр. «курин») увела бы «яйцо» на куриное филе при отсутствии яиц.
  if (q.length === 1 && CANONICAL[q[0]]) {
    const hint = CANONICAL[q[0]];
    const preferred = all.filter((s) => s.score > 0 && canonicalStems(s.c.name).includes(hint));
    if (preferred.length) return pickBest(preferred);
  }

  const scored = all.filter((s) => s.score >= CATALOG_THRESHOLD);
  if (scored.length === 0) return null;
  return pickBest(scored);
}
