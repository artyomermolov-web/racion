// Перевод количества ингредиента в единицу продажи (тикет 18). Чистый модуль.
//
// Состав рецепта хранится в граммах/мл (для штучных — «граммовый эквивалент»,
// см. схему RecipeIngredient.grams), а список покупок и пачки считаются в единице
// ПРОДАЖИ. Для г/мл единица совпадает с массой; для штучных переводим массу в
// штуки через массу одной штуки (Ingredient.gramsPerPiece).

/**
 * Количество ингредиента в единице продажи. Для штучных (unit="pcs") с известной
 * массой штуки делит граммовый эквивалент на неё → штуки; иначе (г/мл или нет
 * данных о массе штуки) возвращает исходное количество без деления.
 */
export function saleQuantity(
  grams: number,
  unit: string,
  gramsPerPiece: number | null | undefined,
): number {
  if (unit === "pcs" && gramsPerPiece && gramsPerPiece > 0) return grams / gramsPerPiece;
  return grams;
}
