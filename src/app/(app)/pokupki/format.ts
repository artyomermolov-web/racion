// Общие форматтеры экрана «Покупки» (тикеты 18/19): и список, и кладовка
// показывают количества в единице продажи одинаково — держим формат в одном
// месте, чтобы подписи не разошлись между вкладками.

/** Количество без хвостовых нулей: 900 → «900», 5.5 → «5,5» (ru). */
export const qty = (n: number) => Number(n.toFixed(2)).toLocaleString("ru-RU");

/** Единица продажи для подписи: штучные — «шт», жидкости — «мл», иначе «г». */
export const unitLabel = (unit: string) =>
  unit === "pcs" ? "шт" : unit === "ml" ? "мл" : "г";
