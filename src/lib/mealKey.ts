// Стабильный ключ приёма для трекинга «съел» (тикет 20). НЕ server-only — общий
// для серверной страницы (восстановление отметок при загрузке) и клиента (DayPlan).
//
// План не персистится, но БАЗОВЫЙ день детерминирован по (userId + дата): при
// перезагрузке собирается тот же день. Поэтому ключ выводим из СОДЕРЖИМОГО приёма
// (дата, слот, рецепт, порция) + порядковый номер на случай дублей в слоте. Так
// повторная отметка приёма БАЗОВОЙ раскладки после перезагрузки даёт тот же ключ —
// и guard от двойного списания (уникальность MealWriteOff по ключу) переживает
// сессию для этих приёмов.
//
// Граница (осознанное упрощение «тонкого» слоя, план не персистится): если списать
// ПЕРЕГЕНЕРИРОВАННЫЙ/заменённый/добавленный из поиска приём, после перезагрузки
// базовый день не содержит его — запись MealWriteOff останется «осиротевшей» (лоты
// уже списаны верно, двойного вычитания нет, но снять отметку/вернуть их через UI
// уже нельзя до персистентности плана). Guard от двойного списания при этом цел.

import type { Slot } from "@/core/generator";

/**
 * Ключ приёма: `дата|слот|рецепт|порция|номер`. `occurrence` (0,1,…) различает
 * несколько приёмов с одинаковыми слотом/рецептом/порцией в один день (напр.
 * добавленные из поиска). Детерминирован — одинаков на сервере и клиенте.
 */
export function mealKey(
  dateKey: string,
  slot: Slot,
  recipeId: string,
  portion: number,
  occurrence = 0,
): string {
  return `${dateKey}|${slot}|${recipeId}|${portion}|${occurrence}`;
}
