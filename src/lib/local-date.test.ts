// Ключи дней текущей недели (тикет 13): экран «Неделя» ведёт с тапа по дню недели
// в ленту этого дня Дневника, значит индексу дня недели (Пн..Вс) нужна реальная
// локальная дата. Чистая функция — тестируется по входу/выходу, как food-labels.

import { describe, it, expect } from "vitest";
import { weekDateKeys, toKey } from "./local-date";

describe("weekDateKeys", () => {
  it("возвращает 7 ключей Пн..Вс недели, содержащей дату", () => {
    // Среда, 10 сентября 2025 (локальная дата). Неделя: Пн 8 … Вс 14.
    const keys = weekDateKeys(new Date(2025, 8, 10));
    expect(keys).toEqual([
      "2025-09-08", // Пн
      "2025-09-09", // Вт
      "2025-09-10", // Ср (сам день)
      "2025-09-11", // Чт
      "2025-09-12", // Пт
      "2025-09-13", // Сб
      "2025-09-14", // Вс
    ]);
  });

  it("для понедельника первый ключ — сам этот день", () => {
    const keys = weekDateKeys(new Date(2025, 8, 8)); // Пн 8 сентября
    expect(keys[0]).toBe("2025-09-08");
    expect(keys[6]).toBe("2025-09-14");
  });

  it("для воскресенья последний ключ — сам этот день (неделя Пн-первый)", () => {
    const keys = weekDateKeys(new Date(2025, 8, 14)); // Вс 14 сентября
    expect(keys[0]).toBe("2025-09-08");
    expect(keys[6]).toBe("2025-09-14");
  });

  it("корректно переходит через границу месяца и года", () => {
    // Чт 1 января 2026. Неделя: Пн 29 дек 2025 … Вс 4 янв 2026.
    const keys = weekDateKeys(new Date(2026, 0, 1));
    expect(keys[0]).toBe("2025-12-29");
    expect(keys[3]).toBe("2026-01-01");
    expect(keys[6]).toBe("2026-01-04");
  });

  it("ключи согласованы с toKey (тот же локальный формат)", () => {
    const from = new Date(2025, 8, 10);
    const keys = weekDateKeys(from);
    expect(keys[2]).toBe(toKey(from));
  });

  it("не теряет и не дублирует дни через DST-переход (арифметика по локальным полям)", () => {
    // Неделя перехода на летнее время в ЕС (вс 30 марта 2025, часы вперёд): даже если
    // среда пришлась на неделю с 23-часовым воскресеньем, ключи остаются ровно Пн..Вс
    // без сдвига (счёт по календарным полям, не по миллисекундам).
    const keys = weekDateKeys(new Date(2025, 2, 26)); // Ср 26 марта 2025
    expect(keys).toEqual([
      "2025-03-24", // Пн
      "2025-03-25",
      "2025-03-26",
      "2025-03-27",
      "2025-03-28",
      "2025-03-29",
      "2025-03-30", // Вс (день перехода)
    ]);
    // Все 7 ключей уникальны — ни один день не «схлопнулся».
    expect(new Set(keys).size).toBe(7);
  });
});
